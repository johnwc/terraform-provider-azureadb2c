// trustFrameworkKeySetsPath is the Graph collection of policy key containers.
const trustFrameworkKeySetsPath = "/trustFramework/keySets"

// errKeySetExists marks a create that failed because the container already exists.
var errKeySetExists = errors.New("the key set already exists")

type trustFrameworkKeySetResource struct{ client *graphClient }

// NewTrustFrameworkKeySetResource manages one policy key container and its key.
func NewTrustFrameworkKeySetResource() resource.Resource { return &trustFrameworkKeySetResource{} }

