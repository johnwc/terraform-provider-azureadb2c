// isAlphanumeric reports whether s is non-empty and holds only ASCII letters and digits.
func isAlphanumeric(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		if !(r >= 'a' && r <= 'z') && !(r >= 'A' && r <= 'Z') && !(r >= '0' && r <= '9') {
			return false
		}
	}
	return true
}

// validateKeySet checks a key set configuration. Unknown values pass.
func validateKeySet(m *trustFrameworkKeySetModel) diag.Diagnostics {
	var diags diag.Diagnostics
	if known(m.ID) && !hasB2CPrefix(m.ID.ValueString()) {
		diags.AddAttributeError(path.Root("id"), "Invalid key set id",
			fmt.Sprintf("%q must start with %s. Graph adds the prefix when it is missing, so it must be written out to keep the state stable.", m.ID.ValueString(), b2cCustomPrefix))
	} else if known(m.ID) && !isAlphanumeric(m.ID.ValueString()[len(b2cCustomPrefix):]) {
		diags.AddAttributeError(path.Root("id"), "Invalid key set id",
			fmt.Sprintf("%q may only contain letters and digits after %s.", m.ID.ValueString(), b2cCustomPrefix))
	}
	if known(m.Use) {
		if _, ok := normalizeKeyUse(m.Use.ValueString()); !ok {
			diags.AddAttributeError(path.Root("use"), "Invalid key use", fmt.Sprintf("%q must be sig or enc.", m.Use.ValueString()))
		}
	}
	keyType := ""
	if known(m.KeyType) {
		kt, ok := normalizeKeyType(m.KeyType.ValueString())
		if !ok {
			diags.AddAttributeError(path.Root("key_type"), "Invalid key type", fmt.Sprintf("%q must be RSA or oct.", m.KeyType.ValueString()))
		}
		keyType = kt
	}
	hasSecret, hasSecretWO := !m.Secret.IsNull(), !m.SecretWO.IsNull()
	if hasSecret && hasSecretWO {
		diags.AddAttributeError(path.Root("secret_wo"), "Conflicting secrets", "Set only one of secret and secret_wo.")
	}
	if !m.SecretWOVersion.IsNull() && !hasSecretWO {
		diags.AddAttributeError(path.Root("secret_wo_version"), "Missing secret_wo", "secret_wo_version is only valid together with secret_wo.")
	}
	if (hasSecret || hasSecretWO) && keyType != "" && keyType != "oct" {
		attr := "secret"
		if hasSecretWO {
			attr = "secret_wo"
		}
		diags.AddAttributeError(path.Root(attr), "Secret needs key_type oct",
			fmt.Sprintf("A secret can only be uploaded with key_type = \"oct\", not %q. Remove the secret to let B2C generate an RSA key.", m.KeyType.ValueString()))
	}
	if known64(m.NotBefore) && known64(m.Expires) && m.Expires.ValueInt64() <= m.NotBefore.ValueInt64() {
		diags.AddAttributeError(path.Root("expires"), "Invalid expiry", "expires must be later than not_before.")
	}
	return diags
}

func known(v types.String) bool  { return !v.IsNull() && !v.IsUnknown() }
func known64(v types.Int64) bool { return !v.IsNull() && !v.IsUnknown() }

// normalizeKeyUse returns the Graph form of a key use (sig or enc).
func normalizeKeyUse(s string) (string, bool) {
	switch strings.ToLower(s) {
	case "sig":
		return "sig", true
	case "enc":
		return "enc", true
	}
	return "", false
}

// normalizeKeyType returns the Graph form of a key type (RSA or oct).
func normalizeKeyType(s string) (string, bool) {
	switch strings.ToLower(s) {
	case "rsa":
		return "RSA", true
	case "oct":
		return "oct", true
	}
	return "", false
}

func (r *trustFrameworkKeySetResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan trustFrameworkKeySetModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	// Write-only values are null in the plan; read them from the config.
	var secretWO types.String
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("secret_wo"), &secretWO)...)
	if resp.Diagnostics.HasError() {
		return
	}
	plan.SecretWO = secretWO
	resp.Diagnostics.Append(validateKeySet(&plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	spec := keySetSpecFromModel(&plan)
	key, err := createKeySet(ctx, r.client, spec)
	if err != nil {
		if errors.Is(err, errKeySetExists) {
			resp.Diagnostics.AddError("Key set already exists",
				fmt.Sprintf("The key set %s already exists in the tenant. Import it to manage it with Terraform:\n\n  terraform import azureadb2c_trust_framework_key_set.<name> %s\n\n%s", spec.ID, spec.ID, err))
			return
		}
		resp.Diagnostics.AddError("Key set create failed", err.Error())
		return
	}
	plan.SecretWO = types.StringNull()
	plan.KeyID = types.StringNull()
	if key.Kid != "" {
		plan.KeyID = types.StringValue(key.Kid)
	} else if ks, err := readKeySet(ctx, r.client, spec.ID); err == nil {
		if k := selectKey(ks, "", time.Now()); k != nil && k.Kid != "" {
			plan.KeyID = types.StringValue(k.Kid)
		}
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *trustFrameworkKeySetResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state trustFrameworkKeySetModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	ks, err := readKeySet(ctx, r.client, state.ID.ValueString())
	if err != nil {
		if isKeySetNotFound(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Key set read failed", err.Error())
		return
	}
	keySetStateFromServer(&state, ks, time.Now())
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// keySetStateFromServer maps a read key set onto the state. use and key_type
// keep the prior value when it differs only in case; not_before and expires are
// only refreshed when they are set in state; the secret is never read back. The
// key matching the key_id in state is preferred (see selectKey).
func keySetStateFromServer(m *trustFrameworkKeySetModel, ks trustFrameworkKeySet, now time.Time) {
	m.SecretWO = types.StringNull()
	knownKid := ""
	if known(m.KeyID) {
		knownKid = m.KeyID.ValueString()
	}
	k := selectKey(ks, knownKid, now)
	if k == nil {
		m.KeyID = types.StringNull()
		return
	}
	if k.Use != "" && !strings.EqualFold(m.Use.ValueString(), k.Use) {
		u, ok := normalizeKeyUse(k.Use)
		if !ok {
			u = k.Use
		}
		m.Use = types.StringValue(u)
	}
	if k.Kty != "" && !strings.EqualFold(m.KeyType.ValueString(), k.Kty) {
		kt, ok := normalizeKeyType(k.Kty)
		if !ok {
			kt = k.Kty
		}
		m.KeyType = types.StringValue(kt)
	}
	if k.Kid != "" {
		m.KeyID = types.StringValue(k.Kid)
	} else {
		m.KeyID = types.StringNull()
	}
	if !m.NotBefore.IsNull() && k.Nbf != nil {
		m.NotBefore = types.Int64Value(*k.Nbf)
	}
	if !m.Expires.IsNull() && k.Exp != nil {
		m.Expires = types.Int64Value(*k.Exp)
	}
}

// Update stores the plan. Every configurable change replaces the key set, so
// this only runs for changes in letter case of use or key_type.
func (r *trustFrameworkKeySetResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state trustFrameworkKeySetModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	plan.SecretWO = types.StringNull()
	if plan.KeyID.IsUnknown() {
		plan.KeyID = state.KeyID
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *trustFrameworkKeySetResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state trustFrameworkKeySetModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := deleteKeySet(ctx, r.client, state.ID.ValueString()); err != nil {
		resp.Diagnostics.AddError("Key set delete failed", err.Error())
	}
}

